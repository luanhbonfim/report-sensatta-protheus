SELECT /*PRG #6179*/  V.SEQUENCIAL_ROMANEIO,
       V.DATA,
       V.PLACA_VEICULO,
       V.NUMERO_LACRE,
       V.NUMERO_MATANCA,
       V.RAZAO_REPRESENTANTE,
       V.FANTASIA_CLIENTE,
       V.ENDERECO_CLIENTE,
       V.CIDADE,
       V.UF,
       V.RAZAO_TRANSPORTADORA,
       V.SEQUENCIAL_PEDIDO,
       V.ORDEM_CARREGAMENTO,
       V.NUMERO_PEDIDO,
       V.NOTA_SAIDA,
       V.SEQUENCIAL_ITEM_PEDIDO,
       SUM(V.QTDE_PRODUTO) QTDE_PRODUTO,
       V.CODIGO_PRODUTO,
       V.DESCRICAO_PRODUTO,
       V.SEQUENCIAL_PRODUTO,
       REGEXP_REPLACE(
         RTRIM(
           REGEXP_REPLACE(
             REGEXP_REPLACE(
               REGEXP_REPLACE(
                 LTRIM(REGEXP_REPLACE(better.concatena_seqembarque(V.sequencial_item_pedido,V.sequencial_romaneio), '#[0-9]+-', ' / 1 - '), ' /') || ' / ',
                 '- ([0-9.]+) / ', '- \1,000 / '),
               '- ([0-9.]+,[0-9]) / ', '- \100 / '),
             '- ([0-9.]+,[0-9][0-9]) / ', '- \10 / '),
           ' /'),
         '(([^/]+/ ){10})', '\1' || CHR(10)) tst,
       V.DATA_SAIDA_NF,
       SUM(SUM(V.QTDE_COMPOSICAO)) OVER(PARTITION BY V.SEQUENCIAL_ROMANEIO,V.SEQUENCIAL_PEDIDO,V.CODIGO_PRODUTO ORDER BY V.SEQUENCIAL_ROMANEIO,V.SEQUENCIAL_PEDIDO,V.CODIGO_PRODUTO) QTDE_COMPOSICAO,
       to_char(SUM(SUM(V.PESO_LIQUIDO)) OVER(PARTITION BY V.SEQUENCIAL_ROMANEIO,V.SEQUENCIAL_PEDIDO,V.CODIGO_PRODUTO ORDER BY V.SEQUENCIAL_ROMANEIO,V.SEQUENCIAL_PEDIDO,V.CODIGO_PRODUTO),'FM999G999G990D900') PESO_LIQUIDO,
       to_char(SUM(SUM(V.PESO_BRUTO)) OVER(PARTITION BY V.SEQUENCIAL_ROMANEIO,V.SEQUENCIAL_PEDIDO,V.CODIGO_PRODUTO ORDER BY V.SEQUENCIAL_ROMANEIO,V.SEQUENCIAL_PEDIDO,V.CODIGO_PRODUTO),'FM999G999G990D900') PESO_BRUTO,
       to_char(SUM(SUM(V.PESO_LIQUIDO)) OVER(PARTITION BY V.SEQUENCIAL_ROMANEIO,V.SEQUENCIAL_PEDIDO,V.CODIGO_PRODUTO ORDER BY V.SEQUENCIAL_ROMANEIO,V.SEQUENCIAL_PEDIDO,V.CODIGO_PRODUTO)/ SUM(SUM(V.QTDE_COMPOSICAO)) OVER(PARTITION BY V.SEQUENCIAL_ROMANEIO,V.SEQUENCIAL_PEDIDO,V.CODIGO_PRODUTO ORDER BY V.SEQUENCIAL_ROMANEIO,V.SEQUENCIAL_PEDIDO,V.CODIGO_PRODUTO),'FM999G999G990D900') MEDIA_PESO,
       SUM(SUM(V.QTDE_COMPOSICAO)) OVER(PARTITION BY V.SEQUENCIAL_PEDIDO) TOTAL_PEDIDO_QTDE_COMPOSICAO,
       to_char(SUM(SUM(V.PESO_LIQUIDO)) OVER(PARTITION BY V.SEQUENCIAL_PEDIDO),'FM999G999G990D900') TOTAL_PEDIDO_PESO_LIQUIDO,
       to_char(SUM(SUM(V.PESO_BRUTO)) OVER(PARTITION BY V.SEQUENCIAL_PEDIDO),'FM999G999G990D900') TOTAL_PEDIDO_PESO_BRUTO,
       to_char(SUM(SUM(V.PESO_LIQUIDO)) OVER(PARTITION BY V.SEQUENCIAL_PEDIDO) / SUM(SUM(V.QTDE_COMPOSICAO)) OVER(PARTITION BY V.SEQUENCIAL_PEDIDO),'FM999G999G990D900') TOTAL_PEDIDO_MEDIA_PESO,
       SUM(SUM(V.QTDE_COMPOSICAO)) OVER(PARTITION BY V.SEQUENCIAL_ROMANEIO) TOTAL_ROMANEIO_QTDE_COMPOSICAO,
       SUM(SUM(V.PESO_LIQUIDO)) OVER(PARTITION BY V.SEQUENCIAL_ROMANEIO) TOTAL_ROMANEIO_PESO_LIQUIDO,
       SUM(SUM(V.PESO_BRUTO)) OVER(PARTITION BY V.SEQUENCIAL_ROMANEIO) TOTAL_ROMANEIO_PESO_BRUTO,
       SUM(SUM(V.PESO_LIQUIDO)) OVER(PARTITION BY V.SEQUENCIAL_ROMANEIO) / SUM(SUM(V.QTDE_COMPOSICAO)) OVER(PARTITION BY V.SEQUENCIAL_ROMANEIO) TOTAL_ROMANEIO_MEDIA_PESO,
       SUM(SUM(V.QTDE_COMPOSICAO)) OVER() TOTAL_QTDE_COMPOSICAO,
       SUM(SUM(V.PESO_LIQUIDO)) OVER() TOTAL_PESO_LIQUIDO,
       SUM(SUM(V.PESO_BRUTO)) OVER() TOTAL_PESO_BRUTO,
       SUM(SUM(V.PESO_LIQUIDO)) OVER() / SUM(SUM(V.QTDE_COMPOSICAO)) OVER() TOTAL_MEDIA_PESO,
       V.COD_PROD_COMPOSICAO,
       V.DESCR_PROD_COMPOSICAO,
       :romaneio_inicial as P_ROMANEIO_INICIAL,
       :romaneio_final as P_ROMANEIO_FINAL
  FROM (
         SELECT DECODE(IPL.SEQUENCIAL_PRODUTO,NULL,IP.SEQUENCIAL_PRODUTO,IPL.SEQUENCIAL_PRODUTO) SEQUENCIAL_PRODUTO,
                R.SEQUENCIAL_ROMANEIO,
                R.DATA,
                R.PLACA_VEICULO,
                R.NUMERO_LACRE,
                R.NUMERO_MATANCA,
                RE.RAZAO_SOCIAL RAZAO_REPRESENTANTE,
                C.NOME_FANTAZIA FANTASIA_CLIENTE,
                C.ENDERECO||' '||C.NUMERO ENDERECO_CLIENTE,
                C.CIDADE,
                C.UF,
                T.RAZAO_SOCIAL RAZAO_TRANSPORTADORA,
                P.SEQUENCIAL_PEDIDO,
                P.ORDEM_CARREGAMENTO,
                P.NUMERO_PEDIDO,
                SIGMA_VEN.NOTAS_PEDIDO(P.SEQUENCIAL_PEDIDO) NOTA_SAIDA,
                SIGMA_VEN.DATA_PEDIDO(P.SEQUENCIAL_PEDIDO) DATA_SAIDA_NF,
                IP.SEQUENCIAL_ITEM_PEDIDO,
                IP.QUANTIDADE_FATURAR QTDE_PRODUTO,
                PR.CODIGO_PRODUTO,
                PP.DESCRICAO DESCRICAO_PRODUTO,
                DECODE(SUM(IPL.QUANTIDADE),NULL,IP.QUANTIDADE_FATURAR,SUM(IPL.QUANTIDADE)) QTDE_COMPOSICAO,
                DECODE(SUM(IPL.PESO),NULL,IP.QUANTIDADE_PESO,SUM(IPL.PESO)) PESO_LIQUIDO,
                SUM(DECODE(NVL(LE.TARA_TOTAL,0), 0, SIGMA_VEN.PESO_BRUTO_PRODUTO(IPL.SEQUENCIAL_PRODUTO, IPL.PESO, IPL.QUANTIDADE)
                                                  , NVL(IPL.PESO,0) + NVL(LE.TARA_TOTAL,0))) PESO_BRUTO,
                DECODE(PR.CODIGO_PRODUTO,NULL,PP.CODIGO_PRODUTO,PR.CODIGO_PRODUTO) COD_PROD_COMPOSICAO,
                '('||PR.DESCRICAO_CERTIFICADO||')' DESCR_PROD_COMPOSICAO
          FROM  SIGMA_VEN.PEDIDO P,
                SIGMA_VEN.TRANSPORTADORA T,
                SIGMA_FIN.CLIENTE C,
                SIGMA_FIN.REPRESENTANTE RE,
                SIGMA_VEN.ROMANEIO R,
                SIGMA_VEN.PRODUTO PR,
                SIGMA_VEN.EMBALAGEM E,
                SIGMA_VEN.ITEM_PEDIDO_LOTE IPL,
                SIGMA_VEN.PRODUTO PP,
                SIGMA_PCP.LOTE_ENTRADA LE,
                SIGMA_VEN.ITEM_PEDIDO IP,
               (SELECT VISUALIZAR_REGIOES FROM SIGMA_RH.FUNCIONARIO WHERE USERNAME = USER) FU
         WHERE  P.CODIGO_REPRESENTANTE = RE.CODIGO_REPRESENTANTE
           AND  P.CODIGO_CLIENTE            = C.CODIGO_CLIENTE
           AND  P.SEQUENCIAL_ROMANEIO       = R.SEQUENCIAL_ROMANEIO
           AND  R.SEQUENCIAL_TRANSPORTADORA = T.SEQUENCIAL_TRANSPORTADORA(+)
           AND  P.SEQUENCIAL_PEDIDO         = IP.SEQUENCIAL_PEDIDO
           AND  IP.SEQUENCIAL_PRODUTO       = PP.SEQUENCIAL_PRODUTO
           AND  IP.SEQUENCIAL_ITEM_PEDIDO   = IPL.SEQUENCIAL_ITEM_PEDIDO(+)
           AND  IPL.SEQUENCIAL_PRODUTO      = PR.SEQUENCIAL_PRODUTO(+)
           AND  PP.ID_EMBALAGEM             = E.ID_EMBALAGEM(+)
           AND  IP.QUANTIDADE_FATURAR       > 0
           AND  IPL.ID_ITEM_PEDIDO_LOTE     = LE.ID_ITEM_PEDIDO_LOTE(+)
           AND  R.SEQUENCIAL_ROMANEIO       BETWEEN :romaneio_inicial AND :romaneio_final
           AND (((FU.VISUALIZAR_REGIOES = 0) AND EXISTS (SELECT 1
                                                                                                   FROM SIGMA_FIN.REGIAO_USUARIO RU
                                                                                                   WHERE RU.SEQUENCIAL_REGIAO_VENDA = P.SEQUENCIAL_REGIAO_VENDA
                                                                                                   AND RU.USUARIO = USER)) OR (FU.VISUALIZAR_REGIOES = 1))
      GROUP BY  R.SEQUENCIAL_ROMANEIO,
                R.DATA,
                R.PLACA_VEICULO,
                R.NUMERO_LACRE,
                R.NUMERO_MATANCA,
                RE.RAZAO_SOCIAL,
                C.NOME_FANTAZIA,
                C.ENDERECO||' '||C.NUMERO,
                C.CIDADE,
                C.UF,
                T.RAZAO_SOCIAL,
                P.SEQUENCIAL_PEDIDO,
                P.ORDEM_CARREGAMENTO,
                P.NUMERO_PEDIDO,
                IP.SEQUENCIAL_ITEM_PEDIDO,
                IP.QUANTIDADE_FATURAR,
                PP.CODIGO_PRODUTO,
                PP.DESCRICAO,
                IP.SEQUENCIAL_PRODUTO,
                IPL.SEQUENCIAL_PRODUTO,
                IP.QUANTIDADE_PESO,
                IPL.SEQUENCIAL_ITEM_PEDIDO,
                PR.CODIGO_PRODUTO,
                PR.DESCRICAO_CERTIFICADO,
                LE.ID_ITEM_PEDIDO_LOTE
        ) V
  GROUP BY V.SEQUENCIAL_ROMANEIO,
           V.DATA,
           V.PLACA_VEICULO,
           V.NUMERO_LACRE,
           V.NUMERO_MATANCA,
           V.RAZAO_REPRESENTANTE,
           V.FANTASIA_CLIENTE,
           V.ENDERECO_CLIENTE,
           V.CIDADE,
           V.UF,
           V.RAZAO_TRANSPORTADORA,
           V.SEQUENCIAL_PEDIDO,
           V.ORDEM_CARREGAMENTO,
           V.NUMERO_PEDIDO,
           V.NOTA_SAIDA,
           V.CODIGO_PRODUTO,
           V.DESCRICAO_PRODUTO,
           V.SEQUENCIAL_PRODUTO,
           V.COD_PROD_COMPOSICAO,
           V.SEQUENCIAL_ITEM_PEDIDO,
           V.DESCR_PROD_COMPOSICAO,
           V.DATA_SAIDA_NF
  ORDER BY V.SEQUENCIAL_ROMANEIO,
           V.ORDEM_CARREGAMENTO,
           V.SEQUENCIAL_PEDIDO,
           V.CODIGO_PRODUTO,
           V.COD_PROD_COMPOSICAO
