-- Report: Resumo de Coletas - EUA
-- Parametros: :data_ini (DATE), :data_fim (DATE)
--
-- IMPORTANTE: o ORDER BY lidera pelas chaves de grupo do .rtm
-- (Group1 = CODIGO_PRODUTO, Group2 = LOTE_EUA) para que o motor
-- de bandas agrupe corretamente. O criterio original (ultima
-- pesagem desc) fica preservado DENTRO do grupo.

WITH CAIXA AS
 (SELECT LE.ID_LOTE_ENTRADA, LE.NUMERO_CAIXA, LH.CONTRA_MARCA, LOTE.LOTE_EUA, LE.DATA_PRODUCAO
    FROM SIGMA_PCP.LOTE_ENTRADA LE
   INNER JOIN BETTER.LOTE_ENTRADA_SHIPPING_HIST LH
      ON LE.ID_LOTE_ENTRADA = LH.ID_LOTE_ENTRADA
    LEFT JOIN (SELECT DISTINCT PA.ID_LOTE_ENTRADA,
                              NVL(SIGMA_PCP.PKG_LOTE_SEPARACAO.ETIQUETA_LOTE(LS.DATA_LOTE,
                                                                             PR.CODIGO_PRODUTO,
                                                                             LS.SEQUENCIA_LOTE,
                                                                             'DDMMYYPPSS'),
                                  'SEM LOTE') AS LOTE_EUA
                FROM SIGMA_PCP.PRODUCAO_AUTOMATICA PA
               INNER JOIN SIGMA_PCP.PRE_ETIQUETA PE
                  ON PA.ID_PRE_ETIQUETA = PE.ID_PRE_ETIQUETA
               INNER JOIN SIGMA_PCP.LOTE_SEPARACAO LS
                  ON PE.ID_LOTE_SEPARACAO = LS.ID_LOTE_SEPARACAO
               INNER JOIN SIGMA_VEN.PRODUTO PR
                  ON LS.SEQUENCIAL_PRODUTO = PR.SEQUENCIAL_PRODUTO) LOTE
      ON LE.ID_LOTE_ENTRADA = LOTE.ID_LOTE_ENTRADA
   WHERE 1 = 1
     AND LH.EXCLUSAO = 0),
AMOSTRA_GERADA AS
 (SELECT PRE.ID_PRE_ETIQUETA AS ID_PRE_ETIQUETA,
         MAX(PA.DATA_CRIACAO) AS DATA_GERADA,
         PR.CODIGO_PRODUTO || ' - ' || PR.DESCRICAO AS PRODUTO,
         PR.CODIGO_PRODUTO,
         PA.ID_LOTE_ENTRADA
    FROM SIGMA_PCP.PRE_ETIQUETA PRE
   INNER JOIN SIGMA_PCP.PRODUCAO_AUTOMATICA PA
      ON PRE.ID_PRE_ETIQUETA = PA.ID_PRE_ETIQUETA
   INNER JOIN SIGMA_VEN.PRODUTO PR
      ON PRE.SEQUENCIAL_PRODUTO = PR.SEQUENCIAL_PRODUTO
   WHERE 1 = 1
     AND (PRE.AMOSTRA = 'S' OR PRE.AMOSTRA_AUTOMATICA = 1)
     AND UPPER(PA.MENSAGEM_ERRO) = 'CAIXA SELECIONADA PARA AMOSTRA'
   GROUP BY PRE.ID_PRE_ETIQUETA,
            PR.CODIGO_PRODUTO || ' - ' || PR.DESCRICAO,
            PR.CODIGO_PRODUTO,
            PA.ID_LOTE_ENTRADA),
AMOSTRA_COLETADA AS
 (SELECT *
    FROM (SELECT PRE.ID_PRE_ETIQUETA AS ID_PRE_ETIQUETA,
                 C.DATA_OPERACAO AS DATA_COLETA,
                 C.USUARIO AS USUARIO_COLETA,
                 C.OPERACAO,
                 ROW_NUMBER() OVER(PARTITION BY PRE.ID_PRE_ETIQUETA ORDER BY C.DATA_OPERACAO DESC) RN
            FROM SIGMA_PCP.PRE_ETIQUETA PRE
           INNER JOIN SIGMA_PCP.HISTORICO_COLETA_AMOSTRA C
              ON PRE.ID_PRE_ETIQUETA = C.ID_PRE_ETIQUETA) SUB
   WHERE SUB.RN = 1),
ULTIMA_PESAGEM AS
 (SELECT PRE.ID_PRE_ETIQUETA AS ID_PRE_ETIQUETA,
         MAX(PA.DATA_CRIACAO) AS DATA_ULTIMA_PESAGEM
    FROM SIGMA_PCP.PRE_ETIQUETA PRE
   INNER JOIN SIGMA_PCP.PRODUCAO_AUTOMATICA PA
      ON PRE.ID_PRE_ETIQUETA = PA.ID_PRE_ETIQUETA
   WHERE 1 = 1
     AND (PRE.AMOSTRA = 'S' OR PRE.AMOSTRA_AUTOMATICA = 1)
     AND UPPER(PA.MENSAGEM_ERRO) =
         'AMOSTRA COLETADA E RETORNADA PARA IMPRESSÃO DA TESTEIRA'
   GROUP BY PRE.ID_PRE_ETIQUETA)

SELECT CX.NUMERO_CAIXA,
       CX.CONTRA_MARCA,
       CX.LOTE_EUA,
       G.ID_PRE_ETIQUETA,
       G.DATA_GERADA,
       G.PRODUTO,
       G.CODIGO_PRODUTO,
       C.DATA_COLETA,
       C.USUARIO_COLETA,
       NVL(TO_CHAR(U.DATA_ULTIMA_PESAGEM, 'DD/MM/YYYY HH24:MI:SS'), 'SEM PESAGEM') DATA_ULTIMA_PESAGEM
  FROM AMOSTRA_GERADA G
 INNER JOIN AMOSTRA_COLETADA C
    ON G.ID_PRE_ETIQUETA = C.ID_PRE_ETIQUETA
 LEFT JOIN ULTIMA_PESAGEM U
    ON G.ID_PRE_ETIQUETA = U.ID_PRE_ETIQUETA
 INNER JOIN CAIXA CX
    ON G.ID_LOTE_ENTRADA = CX.ID_LOTE_ENTRADA
 WHERE 1 = 1
   AND CX.DATA_PRODUCAO >= :data_ini
   AND CX.DATA_PRODUCAO <= :data_fim
 ORDER BY G.CODIGO_PRODUTO, CX.LOTE_EUA, U.DATA_ULTIMA_PESAGEM DESC
